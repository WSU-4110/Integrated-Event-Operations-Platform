import { readFileSync } from "node:fs";
import { drizzle } from "drizzle-orm/node-postgres";
import { migrate } from "drizzle-orm/node-postgres/migrator";
import pg from "pg";
import * as schema from "./schema";

const { Pool } = pg;

if (!process.env.DATABASE_URL) {
  throw new Error(
    "DATABASE_URL must be set. Did you forget to provision a database?",
  );
}

// In production, DATABASE_SSL_CA points at the AWS RDS certificate bundle so the
// connection is encrypted and the server's certificate is verified. Leave
// sslmode out of DATABASE_URL; it would override this setting.
const sslCaPath = process.env.DATABASE_SSL_CA;

export const pool = new Pool({
  connectionString: process.env.DATABASE_URL,
  ssl: sslCaPath ? { ca: readFileSync(sslCaPath, "utf8") } : undefined,
  // Fail with an error instead of waiting forever when the database can't be
  // reached (for example, a network or firewall problem).
  connectionTimeoutMillis: 10_000,
});
// An idle connection can drop (database restart, maintenance, network).
// Without a listener, node-postgres's "error" event would crash the whole
// server; log it instead, and the pool opens a new connection when needed.
pool.on("error", (err) => {
  console.error("Database connection error (idle client):", err.message);
});

export const db = drizzle(pool, { schema });

// Applies the SQL files generated by `pnpm --filter @workspace/db run generate`.
export async function runMigrations(migrationsFolder: string) {
  await migrate(db, { migrationsFolder });
}

